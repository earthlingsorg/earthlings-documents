def _prohibited_typography(ctx):
    """Признаки машинного набора, о которых память говорит отдельно.

    Ёлочки законны, а вот кавычки-лапки, длинное тире и неразрывный пробел -
    нет, и общий раздел 6 их уже ловит. Здесь другое: ДВОЙНОЙ дефис и
    дефис вместо тире с неверными пробелами, которых общий словарь не видит,
    потому что оба знака - законный ASCII.
    """
    bad = []
    for n, s in sorted(ctx.texts.items()):
        c = len(re.findall(r'(?<!-)--(?!-)', s))
        if c:
            bad.append((n, '--', c))
        # Тире между словами обязано стоять с пробелами с обеих сторон.
        c = len(re.findall(r'[а-яё]-\s|\s-[а-яё]', s))
        if c:
            bad.append((n, 'дефис как тире', c))
    print('  ' + (str(bad) if bad else 'чисто'))


def _corpus_counter(ctx):
    """Счётчик документов корпуса живёт в двух формах записи и при трёх
    прилагательных. Он уже расходился дважды: при вводе документа 02 и при
    снятии документа 17. Печатаем все числа рядом со словом «документ»."""
    seen = {}
    for n, s in sorted(ctx.texts.items()):
        for m in re.finditer(
                r'(\d{2}|двадцать\s+\w+|двадцати\w*)\s+'
                r'(?:основополагающ\w+\s+|институциональн\w+\s+|)документ\w*', s):
            seen.setdefault(m.group(1).strip(), []).append(n)
    if not seen:
        print('  счётчик корпуса в тексте не найден')
        return
    for val in sorted(seen):
        print('  %-22s %s' % (val, ', '.join(sorted(set(seen[val])))[:80]))
    if len(seen) > 1:
        print('  ВНИМАНИЕ: счётчик записан разными числами - сверить с CHAIN')


def _period_dates(ctx):
    """Даты учредительного периода. Их четыре, они стоят в четырёх документах
    и сдвигались уже дважды. Печатаем перепись, чтобы расхождение было видно
    без grep-а по восьми языкам."""
    pat = (r'(\d{1,2})\s+(январ|феврал|март|апрел|ма[йя]|июн|июл|август|'
           r'сентябр|октябр|ноябр|декабр)\w*\s+(202[5-9])')
    seen = {}
    for n, s in sorted(ctx.texts.items()):
        for m in re.finditer(pat, s):
            key = '%s %s %s' % (m.group(1), m.group(2), m.group(3))
            seen[key] = seen.get(key, 0) + 1
    for k in sorted(seen, key=lambda x: (-seen[x], x)):
        print('  %-24s %d' % (k, seen[k]))
    if not seen:
        print('  дат в тексте не найдено')


