def _count_jan(text):
    u"""«Народ» - जन. Считаем ПОИМЁННЫМИ формами, а не допуском.

    Допуск в два знака нужен ради косвенного множественного जनों, но ровно
    столько же знаков у जनता - и тогда счёт «народа» молча вбирает в себя
    «широкую публику», то есть жёстко запрещённый вариант. Проверка
    поглощений нашла это единственным случаем во всём словаре.

    Формы у जन ровно две: послелоги в хинди пишутся отдельно, и словоизменение
    ограничено косвенным множественным. Тот же приём, что у грузинского ერი
    (см. ka.py, COUNT_OVERRIDE).
    """
    return len(re.findall(
        H.forms(_JAN, ['', _OBLIQUE_PL]).replace(
            r'(?<![\w-])', '(?<![' + BOUNDARY + '])').replace(
            r'(?![\w-])', '(?![' + BOUNDARY + '])'),
        text))


