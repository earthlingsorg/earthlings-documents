_HARAKAT = {0x064B: 'танвин фатх', 0x064C: 'танвин дамм',
            0x064D: 'танвин касра', 0x064E: 'фатха', 0x064F: 'дамма',
            0x0650: 'касра', 0x0651: 'шадда', 0x0652: 'сукун',
            0x0670: 'кинжальный алиф'}


_RE_WORD = re.compile('[' + H.ARABIC_LETTERS + H.ARABIC_HARAKAT + ']+')


def _harakat(ctx):
    """Огласовки: сплошная огласовка - признак учебного или религиозного текста.

    Не запрет, а выкладка на разбор. Считать надо не знаки, а ПЛОТНОСТЬ их в
    слове: одна огласовка на слово почти всегда снимает двусмысленность, три и
    больше - это уже огласованный текст, чужой нам регистр.

    Три разряда, и они разные по смыслу:

    - **танвин фатх** (U+064B) на наречном винительном - وفقاً, أيضاً, خلافاً -
      обычная норма опубликованной арабской прозы, включая тексты ООН. Не
      дефект вовсе;
    - **слова с одной-двумя огласовками** - разграничение. Главный случай в
      правовом тексте: пассив против актива, يُعتمد («принимается») против
      يعتمد («принимает»). Для нашего корпуса это не украшение: русский мастер
      строит запреты безличным пассивом, и снятая огласовка превращает запрет
      в утверждение о действии народа. См. КАРТА_ОПАСНЫХ_МЕСТ.md, раздел B;
    - **слова с тремя и более огласовками** - сплошная огласовка. Вот это
      разбирается поштучно.
    """
    tanwin = 0
    light, heavy = 0, []
    per_sign = {}
    for name, s in sorted(ctx.texts.items()):
        for m in _RE_WORD.finditer(s):
            w = m.group(0)
            marks = [ord(c) for c in w if ord(c) in _HARAKAT]
            tanwin += marks.count(0x064B)
            rest = [o for o in marks if o != 0x064B]
            for o in rest:
                per_sign[o] = per_sign.get(o, 0) + 1
            if not rest:
                continue
            if len(rest) < 3:
                light += 1
            else:
                heavy.append((name, w))
    print('  танвин фатх (норма прозы):            %d' % tanwin)
    print('  слов с 1-2 огласовками (разграничение): %d' % light)
    print('  слов со СПЛОШНОЙ огласовкой (3+):     %d%s'
          % (len(heavy), '' if not heavy else '   <-- разобрать поштучно'))
    for name, w in heavy[:20]:
        print('      %-28s %s' % (name[:28], w))
    for o, n in sorted(per_sign.items(), key=lambda kv: -kv[1]):
        print('      U+%04X %-18s %d' % (o, _HARAKAT[o], n))


def _direction_marks(ctx):
    """LRM и RLM: каждое вхождение обосновано в словаре решений или его нет.

    Запрещать целиком нельзя - изредка знак действительно нужен, чтобы
    латинская вставка не растащила пунктуацию соседней фразы. Но чаще это
    след копирования из чужой разметки: в HTML Устава на un.org знаки U+200F
    стоят внутри статьи 2, и вместе с цитатой они переезжают к нам.
    """
    marks = {0x200E: 'LRM', 0x200F: 'RLM', 0x061C: 'ALM'}
    total = 0
    for name, s in sorted(ctx.texts.items()):
        for i, ch in enumerate(s):
            if ord(ch) in marks:
                total += 1
                c = ' '.join(s[max(0, i - 30):i + 30].split())
                print('  %-24s %s  %s' % (name[:24], marks[ord(ch)], c[:70]))
    print('  всего знаков направления: %d%s'
          % (total, '' if not total
             else '   <-- каждое обосновать в словаре или снять'))


def _latin_glue(ctx):
    """Латинская вставка внутри арабской строки: пробелы с обеих сторон.

    Имя народа, адрес сайта и адреса контрактов пишутся латиницей внутри
    арабского текста. Слипание الشعبEarthlings глазами почти не видно в RTL -
    браузер разводит куски по разным сторонам строки, - а поиск и перенос
    ломаются оба.
    """
    glue = 0
    for name, s in sorted(ctx.texts.items()):
        for m in re.finditer(r'(?<![\s\w-])[A-Za-z][A-Za-z0-9]*[' +
                             H.ARABIC_LETTERS + r']|[' + H.ARABIC_LETTERS +
                             r'][A-Za-z][A-Za-z0-9]*', s):
            glue += 1
            c = ' '.join(s[max(0, m.start() - 30):m.end() + 30].split())
            print('  СЛИПАНИЕ %-22s %s' % (name[:22], c[:76]))
    print('  слипаний латиницы с арабской буквой: %d' % glue)


