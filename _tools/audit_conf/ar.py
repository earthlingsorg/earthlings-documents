# Окончания БЕЗ относительного 'ية': для основ, у которых относительное
# прилагательное значит другое слово. شعب + ية = شعبية, «популярность», и
# рядом شعبوية, «популизм»; ни то ни другое к народу отношения не имеет.
_ENDS_NOREL = ['', 'ه', 'ها', 'هم', 'هما', 'نا', 'كم', 'ان', 'ين', 'ون']


def _phrase(first, second, extra=5):
    """Двухсловный термин с артиклем внутри.

    Писать такие термины основой нельзя: 'جمعية عامة' не найдёт
    'الجمعية العامة', потому что артикль стоит и перед вторым словом тоже, а
    основа знает только начало строки. Здесь артикль второго слова
    необязателен, и оба слова получают допуск окончания.
    """
    return (r'(?<![\w-])' + H.ARABIC_PROCLITIC + re.escape(first) +
            '[' + H.ARABIC + ']{0,%d}' % extra + r'\s+(?:' +
            chr(0x0627) + chr(0x0644) + r')?' + re.escape(second) +
            '[' + H.ARABIC + ']{0,%d}' % extra + r'(?![\w-])')


def _n(pattern):
    """Замыкание счёта по готовому выражению - для COUNT_OVERRIDE."""
    rx = re.compile(pattern)
    return lambda text: len(rx.findall(text))


def _n_any(*patterns):
    """Счёт нескольких выражений как одного термина.

    Нужно там, где множественное число ЛОМАНОЕ и основой не ловится:
    شعب -> شعوب, أمة -> أمم. Без сложения норма корпуса и её собственное
    множественное показали бы разные числа, и раздел напечатал бы
    расползание там, где написано одно слово.
    """
    rxs = [re.compile(p) for p in patterns]
    return lambda text: sum(len(rx.findall(text)) for rx in rxs)

