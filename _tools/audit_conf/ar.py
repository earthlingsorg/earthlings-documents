def _forms(base, endings):
    """Основа со списком окончаний И с приставочными частицами.

    H.forms() приставок не знает: он писался для грузинского, где их нет.
    Здесь без приставок теряется والشعب, بالشعب, للشعب - то есть больше
    половины вхождений.
    """
    alt = '|'.join(re.escape(e) for e in sorted(endings, key=len, reverse=True))
    return (r'(?<![\w-])' + H.ARABIC_PROCLITIC + re.escape(base) +
            '(?:' + alt + r')(?![\w-])')


