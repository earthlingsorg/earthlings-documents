# Ломаное множественное основой не ловится, а имя ООН содержит أمم пять
# десятков раз - и то и другое чинится здесь, а не в отчёте.
_RE_SHAAB = _forms('شعب', _ENDS_NOREL)
_RE_SHUUB = _forms('شعوب', _ENDS_NOREL)
_RE_UMMA = _forms('أمة', ['', 'ه', 'ها', 'نا'])
_RE_UMAM = _forms('أمم', ['', 'ها'])


def _count_umma(text):
    """أمة и أمم, но без имени Организации Объединённых Наций.

    الأمم المتحدة стоит в корпусе десятками раз, и без отсева слово «нация»
    показывает расползание там, где написано имя ООН. Отсеиваем по соседству
    справа: за нашим أمم в имени организации всегда идёт المتحدة.
    """
    n = len(re.findall(_RE_UMMA, text))
    for m in re.finditer(_RE_UMAM, text):
        if not re.match(r'\s+' + chr(0x0627) + chr(0x0644) + 'متحدة',
                        text[m.end():m.end() + 12]):
            n += 1
    return n


