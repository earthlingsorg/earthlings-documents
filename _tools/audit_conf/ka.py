def _latin_glue(ctx):
    """Латинское имя перед грузинским окончанием пишется через дефис всегда.

    Единственная проверка, которой нет ни у одного другого языка корпуса.
    Склейка Earthlingsის от правильного Earthlings-ის глазами не отличается,
    а в отрисовке даёт неправильный перенос.
    """
    glue = 0
    for name, s in sorted(ctx.texts.items()):
        for m in re.finditer(r'(?<![\w-])([A-Za-z][A-Za-z0-9]*)([' +
                             H.MKHEDRULI + r']+)', s):
            glue += 1
            c = ' '.join(s[max(0, m.start() - 30):m.end() + 30].split())
            print('  СКЛЕЙКА %-24s %s' % (name[:24], c[:80]))
    ok = len(re.findall(r'(?<![\w-])[A-Za-z][A-Za-z0-9]*-[' + H.MKHEDRULI +
                        r']+', ctx.allw))
    print('  правильных форм через дефис: %d, склеек: %d' % (ok, glue))


def _mtavruli(ctx):
    n = sum(1 for ch in ctx.allw if H.MTAVRULI[0] <= ch <= H.MTAVRULI[-1])
    print('  знаков мтаврули: %d%s'
          % (n, '' if not n else '   <-- регистр рисует CSS, не мастер'))


