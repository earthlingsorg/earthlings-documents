"""Помощники для конфигураций аудита.

Живут отдельно от audit_lang.py, чтобы конфигурация языка могла их
импортировать, не втягивая машинерию и не создавая кольцо импортов.

Здесь только построение регулярных выражений. Ни одного решения о том, что
считать дефектом: это дело конфигурации языка.
"""
import re

# Диапазоны письменностей строятся из ЧИСЛОВЫХ кодпойнтов, а не из литералов.
# Литерал грузинской или арабской буквы молча портится при передаче через
# heredoc, буфер обмена и редактор с автозаменой, и проверка потом «проходит»
# на испорченном диапазоне, ничего не находя. Это правило корпуса, а не вкус:
# оно уже стоило одной сессии ложного «чисто».
def rng(a, b):
    """Диапазон для символьного класса: rng(0x10D0, 0x10FA) -> 'ა-ჺ'."""
    return '%s-%s' % (chr(a), chr(b))


LATIN = 'A-Za-z'
MKHEDRULI = rng(0x10D0, 0x10FA)      # грузинское рабочее письмо
MTAVRULI = rng(0x1C90, 0x1CBF)       # грузинские заглавные, их рисует CSS
ARABIC = rng(0x0600, 0x06FF)
DEVANAGARI = rng(0x0900, 0x097F)
CJK = rng(0x4E00, 0x9FFF)

GUILLEMET_OPEN, GUILLEMET_CLOSE = chr(0x00AB), chr(0x00BB)
INV_Q, INV_E = chr(0x00BF), chr(0x00A1)
LOW9_OPEN, LOW9_CLOSE = chr(0x201E), chr(0x201C)   # немецкая пара „..."


def word(w):
    """Счёт по границе слова.

    Границу берём как «не буква, не цифра, не дефис»: обычный \\b режет по
    дефису, и тогда 22-бис находится внутри 122-бис, а Earthlings-ის внутри
    чего попало.
    """
    return r'(?<![\w-])' + re.escape(w.strip()) + r'(?![\w-])'


def stem(base, letters, extra=8):
    """Основа с допуском окончания - для агглютинативных и флективных языков.

    Слева граница обязательна: без неё грузинское ერი находится внутри
    ნებისმიერი. Справа допускаются только буквы своего письма, иначе
    латинское имя с окончанием ловится как форма чего попало.
    """
    return (r'(?<![\w-])' + re.escape(base) +
            '[' + letters + ']{0,%d}' % extra + r'(?![\w-])')


def forms(base, endings):
    """Основа со СПИСКОМ окончаний - для коротких и опасных слов.

    Допуском такие ловить нельзя: грузинское ერ- даёт ერთი, ერთობა, ერთიანი,
    и аудит тонет в ложных срабатываниях. Окончания перечисляются поимённо,
    длинные проверяются раньше коротких.
    """
    alt = '|'.join(re.escape(e) for e in sorted(endings, key=len, reverse=True))
    return r'(?<![\w-])' + re.escape(base) + '(?:' + alt + r')(?![\w-])'


