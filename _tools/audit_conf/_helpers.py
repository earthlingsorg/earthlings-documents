def word(w):
    """Счёт по границе слова.

    Границу берём как «не буква, не цифра, не дефис»: обычный \\b режет по
    дефису, и тогда 22-бис находится внутри 122-бис, а Earthlings-ის внутри
    чего попало.
    """
    return r'(?<![\w-])' + re.escape(w.strip()) + r'(?![\w-])'


def ascii_word(w):
    """Счёт латинского слова внутри письменности БЕЗ пробелов.

    Обычный word() здесь даёт ноль всегда, и молча. Его граница - «не \\w», а
    соседний иероглиф это тоже \\w: в 参与DAO治理 перед D стоит 与, лookбехинд не
    срабатывает, и DAO не находится ни разу. Так теряются все латинские
    термины корпуса сразу - DAO, SBT, Polygon, само имя Earthlings, - а отчёт
    показывает «чисто».

    Границу берём по латинице: не буква, не цифра, не подчёркивание и не
    дефис. Иероглиф при этом границей СЧИТАЕТСЯ, а DAO внутри DAOism или
    MYDAO по-прежнему не находится.
    """
    return (r'(?<![0-9A-Za-z_-])' + re.escape(w.strip()) +
            r'(?![0-9A-Za-z_-])')


def stem(base, letters, extra=8, prefix=''):
    """Основа с допуском окончания - для агглютинативных и флективных языков.

    Слева граница обязательна: без неё грузинское ერი находится внутри
    ნებისმიერი. Справа допускаются только буквы своего письма, иначе
    латинское имя с окончанием ловится как форма чего попало.

    `prefix` - выражение приставочных частиц между границей и основой. Нужно
    там, где язык пишет служебные слова СЛИТНО: арабское والشعب - это «и» плюс
    артикль плюс «народ», и граница слова стоит перед و, а не перед ش. Без
    приставки счёт молча теряет все такие формы, а их в арабском корпусе
    больше половины. По умолчанию пусто: языкам, где приставок нет, выражение
    не меняется ни на знак.
    """
    return (r'(?<![\w-])' + prefix + re.escape(base) +
            '[' + letters + ']{0,%d}' % extra + r'(?![\w-])')


# Арабские приставочные частицы, пишущиеся слитно со словом: و (и), ف (и вот),
# ب (посредством), ك (как), ل (для) и определённый артикль ال. Сочетаются:
# والشعب, بالشعب, للشعب, وللشعب. Артикль отделён от остальных, потому что
# начинается с алифа, которого в наборе частиц нет.
ARABIC_PROCLITIC = ('[' + ''.join(chr(c) for c in
                                 (0x0648, 0x0641, 0x0628, 0x0643, 0x0644)) +
                    ']{0,2}(?:' + chr(0x0627) + chr(0x0644) + ')?')


def forms(base, endings):
    """Основа со СПИСКОМ окончаний - для коротких и опасных слов.

    Допуском такие ловить нельзя: грузинское ერ- даёт ერთი, ერთობა, ერთიანი,
    и аудит тонет в ложных срабатываниях. Окончания перечисляются поимённо,
    длинные проверяются раньше коротких.
    """
    alt = '|'.join(re.escape(e) for e in sorted(endings, key=len, reverse=True))
    return r'(?<![\w-])' + re.escape(base) + '(?:' + alt + r')(?![\w-])'


