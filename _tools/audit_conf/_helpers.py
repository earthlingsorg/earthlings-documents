"""Помощники для конфигураций аудита.

Живут отдельно от audit_lang.py, чтобы конфигурация языка могла их
импортировать, не втягивая машинерию и не создавая кольцо импортов.

Здесь только построение регулярных выражений. Ни одного решения о том, что
считать дефектом: это дело конфигурации языка.
"""
import re

# Диапазоны письменностей строятся из ЧИСЛОВЫХ кодпойнтов, а не из литералов.
# Литерал грузинской или арабской буквы молча портится при передаче через
# heredoc, буфер обмена и редактор с автозаменой, и проверка потом «проходит»
# на испорченном диапазоне, ничего не находя. Это правило корпуса, а не вкус:
# оно уже стоило одной сессии ложного «чисто».
def rng(a, b):
    """Диапазон для символьного класса: rng(0x10D0, 0x10FA) -> 'ა-ჺ'."""
    return '%s-%s' % (chr(a), chr(b))


LATIN = 'A-Za-z'
MKHEDRULI = rng(0x10D0, 0x10FA)      # грузинское рабочее письмо
MTAVRULI = rng(0x1C90, 0x1CBF)       # грузинские заглавные, их рисует CSS
ARABIC = rng(0x0600, 0x06FF)
# Только БУКВЫ арабского письма, без пунктуации и огласовок. Нужен там, где
# проверка спрашивает «стоит ли латиница вплотную к арабской букве»: полный
# блок U+0600..U+06FF содержит и запятую ، (U+060C), и точку с запятой ؛, и
# вопросительный знак ؟, а запятая после латинского слова пишется вплотную
# по правилам пунктуации и дефектом не является.
ARABIC_LETTERS = rng(0x0621, 0x063A) + rng(0x0641, 0x064A)
# Огласовки и танвины отдельным классом - раздел «огласовки» в audit_conf/ar.py.
ARABIC_HARAKAT = rng(0x064B, 0x0652) + chr(0x0670)
