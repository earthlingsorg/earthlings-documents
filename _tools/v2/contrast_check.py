u"""Проверка контраста ролей палитры по WCAG 2.1.

В приёмке нового сайта записано «контраст текста и фона проходит AA на всех
ролях палитры». Пожелание, которое нельзя прогнать, через месяц становится
ничем, поэтому вот оно в виде проверки.

Цвета берутся из живого tokens.css, а не переписываются сюда: копия разошлась
бы с оригиналом при первой же правке. Роли раскрываются рекурсивно, потому что
в файле они заданы через var().

Запуск:  python _v2/tools/contrast_check.py
Выход:   0 - все пары проходят, 1 - есть провалы.
"""
