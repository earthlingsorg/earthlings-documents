def read_tokens(path):
    src = io.open(path, encoding='utf-8').read()
    # только объявления внутри :root, чтобы не поймать значения из @font-face
    body = src[src.index(':root'):]
    raw = dict(re.findall(r'--([a-z0-9-]+)\s*:\s*([^;]+);', body))
    assert raw, u'в %s не нашлось ни одной переменной' % path
    return raw


def resolve(raw, name, depth=0):
    assert depth < 10, u'переменная --%s ссылается по кругу' % name
    v = raw.get(name)
    assert v is not None, u'нет переменной --%s' % name
    v = v.split('/*')[0].strip()
    m = re.match(r'^var\(\s*--([a-z0-9-]+)\s*\)$', v)
    if m:
        return resolve(raw, m.group(1), depth + 1)
    m = re.match(r'^#([0-9a-fA-F]{6})$', v)
    assert m, u'роль --%s не сводится к цвету: %r' % (name, v)
    h = m.group(1)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def luminance(rgb):
    out = []
    for c in rgb:
        s = c / 255.0
        out.append(s / 12.92 if s <= 0.03928 else ((s + 0.055) / 1.055) ** 2.4)
    return 0.2126 * out[0] + 0.7152 * out[1] + 0.0722 * out[2]


def ratio(a, b):
    la, lb = luminance(a), luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def main():
    assert os.path.isfile(TOKENS), u'нет файла %s' % TOKENS
    raw = read_tokens(TOKENS)
    lines, bad = [], 0
    lines.append(u'%-34s %-13s %-13s %7s %6s  %s'
                 % (u'пара', u'текст', u'фон', u'контраст', u'порог', u'итог'))
    lines.append(u'-' * 92)
    for title, fg, bg, need in PAIRS:
        a, b = resolve(raw, fg), resolve(raw, bg)
        r = ratio(a, b)
        ok = r + 1e-9 >= need
        bad += 0 if ok else 1
        lines.append(u'%-34s %-13s %-13s %6.2f:1 %6.1f  %s'
                     % (title, '#%02x%02x%02x' % a, '#%02x%02x%02x' % b,
                        r, need, u'да' if ok else u'ПРОВАЛ'))
    lines.append(u'')
    lines.append(u'проверено пар: %d, провалов: %d' % (len(PAIRS), bad))

    assert WAIVED, u'раздел принятых исключений пуст - проверять нечего'
    lines.append(u'')
    lines.append(u'--- принято сознательно, проверку не валит ---------------')
    for title, fg, bg, need in WAIVED:
        a, b = resolve(raw, fg), resolve(raw, bg)
        r = ratio(a, b)
        lines.append(u'%-34s %-13s %-13s %6.2f:1 %6.1f  %s'
                     % (title, '#%02x%02x%02x' % a, '#%02x%02x%02x' % b,
                        r, need,
                        u'проходит' if r + 1e-9 >= need else u'ниже порога'))
    io.open(os.path.join(HERE, 'contrast-report.txt'), 'w',
            encoding='utf-8').write(u'\n'.join(lines) + u'\n')
    # В консоль Windows кириллица не всегда лезет, поэтому отчёт - в файл,
    # а сюда только короткий итог.
    sys.stdout.write('pairs=%d failed=%d -> %s\n'
                     % (len(PAIRS), bad,
                        os.path.join(HERE, 'contrast-report.txt')))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
