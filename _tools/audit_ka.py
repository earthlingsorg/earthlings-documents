"""Машинная вычитка грузинского корпуса.

Сделан из audit_es.py, который на два круга чище остальных: из него перенесены
дословно unquoted() (выбрасывает цитаты и адреса до проверки) и count_word()
(счёт по границе слова). Ловит то же самое, но своими списками и своей
механикой счёта - грузинский устроен иначе, чем любой из закрытых языков.

Пять различий против испанского аудита, каждое существенное:

1. ГЛАВНОЕ: грузинский агглютинативен, и счёт по границе слова тут не работает.
   Одно «народ» живёт как ხალხი, ხალხს, ხალხის, ხალხმა, ხალხად, ხალხთა,
   ხალხები, ხალხებს, ხალხში, ხალხზე, ხალხთან, ხალხიდან, ხალხისთვის,
   ხალხისადმი. Термин ищется по основе с допуском окончания - см. stem().
   Обратная опасность тоже реальна: ერი (нация) сидит внутри ნებისმიერი,
   ყველაფერი, სერიოზული, и наивный поиск подстроки даёт десятки ложных
   срабатываний. Поэтому у коротких и опасных основ окончания перечислены
   поимённо, а не допуском.
2. Заглавных букв в мхедрули нет. Все проверки испанского аудита, опирающиеся
   на прописную (начало предложения, диакритика заглавной), сняты; вместо них
   заведена проверка на мтаврули (U+1C90-1CBF) - его в мастерах быть не должно,
   регистр рисует CSS.
3. Заведён раздел 5-бис, которого нет ни у одного другого языка: латинское имя
   перед грузинским окончанием пишется через дефис (Earthlings-ის, earthling-ი).
   Склейка (Earthlingsის) - дефект, и глазами он почти не виден.
4. Перевёрнутых знаков в грузинском нет, ALLOWED_BY_LANG пуст: перепись по 23
   грузинским страницам сайта дала ноль знаков из запрещённого словаря.
   Кавычки корпуса - ёлочки, как у русского.
5. Пара «правоспособность / дееспособность» разводится словами Гражданского
   кодекса Грузии: უფლებაუნარიანობა (ст. 11) и ქმედუნარიანობა (ст. 12).
   Третье слово, სამართალსუბიექტობა, - правосубъектность, и оно стоит в
   грузинском тексте статьи 16 Пакта и статьи 6 Всеобщей декларации.

Использование: python _tools/audit_ka.py [ka]
"""
