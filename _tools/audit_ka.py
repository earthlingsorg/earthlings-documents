def load():
    out = {}
    for f in sorted(os.listdir(DIR)):
        if f.endswith('.md') and f[0].isdigit():
            out[f] = io.open(os.path.join(DIR, f), encoding='utf-8').read()
    m = os.path.join(REPO, '_manifest', '%s-manifest.md' % LANG)
    if os.path.isfile(m):
        out['manifest'] = io.open(m, encoding='utf-8').read()
    assert out, 'нет мастеров в %s - переводить ещё нечего' % DIR
    assert all(t.strip() for t in out.values()), 'пустой файл на входе'
    return out


def unquoted(s):
    """Текст без дословных цитат из актов и без служебных строк.

    Цитата воспроизводит слова подлинника, и они бывают не нашими: грузинский
    текст статьи 22 Пакта говорит ასოციაცია там, где термин корпуса -
    გაერთიანება. Править цитату нельзя, а считать её расползанием - ложная
    тревога. По той же причине выбрасываются адреса и код.
    """
    s = re.sub(GE_OPEN + r'[^' + GE_CLOSE + r']*' + GE_CLOSE, ' ', s)
    s = re.sub(r'`[^`]*`|\((?:https?|mailto):[^)]*\)|\bhttps?://\S+', ' ', s)
    return s


def count_word(s, w):
    """Счёт по границе слова: без неё 22-ბის находится внутри 122-ბის."""
    return len(re.findall(r'(?<![\w-])' + re.escape(w.strip()) + r'(?![\w-])', s))


def count_stem(s, base, extra=8):
    """Счёт по основе с допуском окончания - см. пояснение к stem()."""
    return len(re.findall(stem(base, extra), s))


def sentences(text):
    """Предложения внутри абзаца, а не через весь файл.

    Резать сразу по всему тексту нельзя: абзац, следующий за точкой и
    начинающийся с врезки `>`, дефиса списка или буквы, приклеивается к
    предыдущему, и счётчик выдаёт несуществующие предложения.

    Прописной буквы в мхедрули нет, поэтому признаком начала предложения
    служит любая буква письма, латинская прописная или ёлочка.
    """
    body = re.sub(r'`[^`]*`|\[[^\]]*\]\([^)]*\)|^\|.*$|^#+ .*$', ' ',
                  text, flags=re.M)
    for para in re.split(r'\n\s*\n|\n(?=\s*(?:[-*]|\d+\.)\s)', body):
        para = ' '.join(para.split())
        if not para:
            continue
        for s in re.split(r'(?<=[.!?])\s+(?=[' + MKHEDRULI + r'A-Z*'
                          + GE_OPEN + r'])', para):
            yield s


def main():
    texts = load()
    allw = ' '.join(texts.values())
    clean = {n: unquoted(s) for n, s in texts.items()}
    allc = ' '.join(clean.values())

    print('файлов: %d, слов: %d' % (len(texts), len(allw.split())))

    print('\n=== 1. ВАРИАНТЫ ОДНОГО СЛОВА ===')
    problems = 0
    for a, b in PAIRS:
        na = count_stem(allc, a.strip()) if a.strip()[-1] not in '0123456789' \
            else count_word(allc, a)
        nb = count_stem(allc, b.strip()) if b.strip()[-1] not in '0123456789' \
            else count_word(allc, b)
        if na and nb:
            problems += 1
            wa = sorted(n for n, s in clean.items() if count_stem(s, a.strip()))
            wb = sorted(n for n, s in clean.items() if count_stem(s, b.strip()))
            print('  СМЕШЕНИЕ %-16s %3d %s' % (a.strip(), na, ','.join(wa)[:52]))
            print('           %-16s %3d %s' % (b.strip(), nb, ','.join(wb)[:52]))
    if not problems:
        print('  чисто')

    print('\n=== 2. ОБОРОТЫ-ТИКИ (>= 10 вхождений) ===')
    shown = 0
    for t in sorted(TICS, key=lambda x: -allw.count(x)):
        n = allw.count(t)
        if n >= 10:
            inf = sum(1 for s in texts.values() if t in s)
            print('  %4d x  "%s"  (файлов: %d)' % (n, t, inf))
            shown += 1
    if not shown:
        print('  чисто')

    print('\n=== 3. РАСПОЛЗАНИЕ ТЕРМИНОВ ===')
    # Считаем по ОЧИЩЕННОМУ тексту: цитата из акта своим словом расползанием
    # не является. ერი отдельно - у него ложные срабатывания внутри ООН.
    drift = 0
    for ru, variants in sorted(GLOSSARY.items()):
        used = []
        for v in variants:
            if v == 'ერ':
                n = len([m for m in re.finditer(RE_ERI, allc)
                         if 'გაერთიან' not in allc[max(0, m.start() - 22):m.start()]])
            else:
                n = count_stem(allc, v)
            if n:
                used.append((v, n))
        if len(used) > 1:
            drift += 1
            print('  %-24s %s' % (ru, '  |  '.join('%s=%d' % (v, c) for v, c in used)))
    if not drift:
        print('  чисто')

    print('\n=== 4. КАЛЬКИ ===')
    found = 0
    for pat, fix in CALQUES:
        hits = [(n, len(re.findall(pat, s))) for n, s in texts.items()]
        hits = [(n, c) for n, c in hits if c]
        if hits:
            found += 1
            total = sum(c for _, c in hits)
            print('  %-36s %3d  -> %s' % (pat[:36], total, fix))
            print('        %s' % ', '.join('%s:%d' % (n, c) for n, c in hits)[:110])
    if not found:
        print('  чисто')

    print('\n=== 5. МЕХАНИКА ===')
    mech = 0
    for name, s in sorted(texts.items()):
        for label, pat in [('двойной пробел', r'[^\n] {2,}[^\n]'),
                           ('пробел перед знаком', r' [,.;:!?](?:\s|$)'),
                           ('повтор слова', r'(?<![\w-])(' + GEO + r'{3,}) \1(?![\w-])')]:
            m = re.findall(pat, s)
            if m:
                mech += 1
                print('  %-30s %-24s %d  %s'
                      % (name[:30], label, len(m), str(m[:3])[:56]))
    if not mech:
        print('  чисто')

    print('\n=== 5-бис. ЛАТИНСКОЕ ИМЯ + ГРУЗИНСКОЕ ОКОНЧАНИЕ ===')
    # Единственная проверка, которой нет ни у одного другого языка корпуса.
    # Earthlings-ის пишется через дефис всегда; склейка глазами не видна.
