# Диапазоны грузинского письма строим из КОДПОЙНТОВ: литералы молча портятся
# при передаче через heredoc и буфер обмена, а проверка потом «проходит».
MKHEDRULI = '%s-%s' % (chr(0x10D0), chr(0x10FA))   # ა-ჺ, рабочее письмо
MTAVRULI = '%s-%s' % (chr(0x1C90), chr(0x1CBF))    # Ა-Ჿ, регистр рисует CSS
