def stem(base, extra=8):
    """Основа с допуском грузинского окончания.

    Слева граница обязательна: без неё ერი находится внутри ნებისმიერი.
    Справа допускаются только буквы мхедрули - латиница и цифры отсекаются,
    иначе Earthlings-ის ловится как форма чего попало.
    """
    return (r'(?<![\w-])' + re.escape(base) +
            '[' + MKHEDRULI + ']{0,%d}' % extra + r'(?![\w-])')


def forms(base, endings):
    """Основа со СПИСКОМ окончаний - для коротких и опасных слов.

    ერი допуском ловить нельзя: ერთა даёт ერთად («вместе»), ერ- даёт ერთი,
    ერთობა, ერთიანი. Здесь окончания перечислены поимённо.
    """
    alt = '|'.join(re.escape(e) for e in sorted(endings, key=len, reverse=True))
    return r'(?<![\w-])' + re.escape(base) + '(?:' + alt + r')(?![\w-])'


